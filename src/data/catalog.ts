const getInitialCatalog = () => {
  if (typeof window !== "undefined") {
    try {
      const raw = localStorage.getItem("ab_db_products");
      if (raw) {
        return JSON.parse(raw);
      }
    } catch {
      // ignore
    }
  }
  return rawCatalog.filter((p) => p.image !== "");
};

export const catalog: CatalogProduct[] = getInitialCatalog();

export const formatCOP = (n: number) =>
  "$" + n.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ".");

export const getProductBySlug = (slug?: string) =>
  catalog.find((p) => p.slug === slug) ?? catalog[0];

export const getRelatedProducts = (slug?: string, limit = 4) => {
  const current = getProductBySlug(slug);
  return catalog
    .filter((p) => p.slug !== current.slug)
    .sort((a, b) => (a.category === current.category ? -1 : 1))
    .slice(0, limit);
};
